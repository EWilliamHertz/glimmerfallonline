/**
 * Filter skill guides by high-level tab group ('All', 'Combat', 'Gathering', 'Artisan').
 */
export function filterSkillGuides(category = 'All') {
  if (!category || category === 'All') return SKILL_GUIDES;
  return SKILL_GUIDES.filter((g) => g.filterGroup === category || g.category === category);
}

/**
 * Find a canonical skill guide entry by skill ID (falling back to Combat Mastery).
 */
export function getSkillGuideById(skillId) {
  return SKILL_GUIDES.find((g) => g.id === skillId) || SKILL_GUIDES[0];
}
