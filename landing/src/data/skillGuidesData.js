/**
 * Clamp and return cumulative XP required for a given skill level (1–99).
 */
export function getSkillXpForLevel(level) {
  const lvl = Math.max(1, Math.min(SKILL_MAX_LEVEL, Math.floor(Number(level) || 1)));
  return SKILL_XP_TABLE_99[lvl - 1] ?? 0;
}

/**
 * Compute remaining XP and estimated actions between two levels.
 */
export function computeSkillActionsNeeded({
  fromLevel = 1,
  toLevel = 99,
  xpPerAction = 100,
  moonOwlBonus = false,
} = {}) {
  const cleanFrom = Math.max(1, Math.min(SKILL_MAX_LEVEL - 1, Math.floor(Number(fromLevel) || 1)));
  const cleanTo = Math.max(cleanFrom + 1, Math.min(SKILL_MAX_LEVEL, Math.floor(Number(toLevel) || SKILL_MAX_LEVEL)));
  const baseXpDelta = Math.max(0, getSkillXpForLevel(cleanTo) - getSkillXpForLevel(cleanFrom));
  const multiplier = moonOwlBonus ? 1.06 : 1.0;
  const effectiveXpPerAction = Math.max(1, xpPerAction * multiplier);
  const actionsNeeded = Math.ceil(baseXpDelta / effectiveXpPerAction);
  return {
    fromLevel: cleanFrom,
    toLevel: cleanTo,
    xpNeeded: baseXpDelta,
    effectiveXpPerAction: Number(effectiveXpPerAction.toFixed(1)),
    actionsNeeded,
    multiplier,
  };
}

